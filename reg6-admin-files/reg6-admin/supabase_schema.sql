-- ---------- 1) ตารางอ้างอิง ----------
create table if not exists public.dept (
  dept_id    smallint generated by default as identity primary key,
  short_name text     not null unique,          -- ชื่อย่อ เช่น รป.
  full_name  text,
  sort_order smallint not null default 0
);

create table if not exists public.doc_type (
  type_id   smallint primary key,
  type_name text not null unique
);

create table if not exists public.news_category (
  cat_id   smallint primary key,
  cat_name text not null unique
);

-- ---------- 2) ข่าวประชาสัมพันธ์ ----------
create table if not exists public.news (
  news_id      bigint generated by default as identity primary key,
  cat_id       smallint not null references public.news_category(cat_id),
  title        text not null,
  image_file   text,                            -- ชื่อไฟล์ใน images/news/
  link_url     text,
  is_published boolean not null default true,
  published_at timestamptz not null default now(),
  created_at   timestamptz not null default now(),
  updated_at   timestamptz
);
create index if not exists ix_news_list on public.news (cat_id, is_published, published_at desc);

-- ---------- 3) หนังสือเวียนและคำสั่ง ----------
create table if not exists public.circular (
  circular_id  bigint generated by default as identity primary key,
  doc_no       text,
  title        text not null,
  type_id      smallint not null references public.doc_type(type_id),
  dept_id      smallint not null references public.dept(dept_id),
  doc_date     date not null,
  is_published boolean not null default true,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz
);
create index if not exists ix_circular_date on public.circular (doc_date desc);

create table if not exists public.circular_file (
  file_id      bigint generated by default as identity primary key,
  circular_id  bigint not null references public.circular(circular_id) on delete cascade,
  kind         text   not null check (kind in ('file', 'link')),
  display_name text,
  url          text   not null
);
create index if not exists ix_cfile_circ on public.circular_file (circular_id);

-- ---------- 4) รวมระบบไปรษณีย์/คู่มือ ----------
create table if not exists public.hub_section (
  section_id  bigint generated by default as identity primary key,
  name        text not null,
  description text,
  sort_order  int  not null default 0
);

create table if not exists public.hub_item (
  item_id    bigint generated by default as identity primary key,
  section_id bigint not null references public.hub_section(section_id) on delete cascade,
  kind       text   not null check (kind in ('app', 'doc')),
  name       text   not null,
  url        text,
  sort_order int    not null default 0
);
create index if not exists ix_hubitem_sec on public.hub_item (section_id, kind, sort_order);

-- ---------- 5) เบอร์โทรศัพท์ / Dashboard ----------
create table if not exists public.phone_directory (
  phone_id      bigint generated by default as identity primary key,
  office_name   text not null,
  postal_code   text,
  position_name text,
  affiliation   text,
  phone_number  text not null
);

create table if not exists public.dashboard (
  dashboard_id bigint generated by default as identity primary key,
  name         text not null,
  embed_url    text,
  sort_order   int  not null default 0
);

-- ---------- 6) ผู้ดูแลระบบ (รายชื่อบัญชีที่มีสิทธิ์แก้ไขข้อมูล) ----------
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.admin_users where user_id = (select auth.uid()));
$$;
revoke execute on function public.is_admin() from public, anon;
grant  execute on function public.is_admin() to authenticated;

-- ---------- 7) ความปลอดภัย (Row Level Security) ----------
-- ผู้ใช้ทั่วไป (anon) เข้าถึงตารางเหล่านี้ไม่ได้เลย หน้าเว็บสาธารณะอ่านจากไฟล์ content.js
-- เฉพาะบัญชีที่อยู่ในตาราง admin_users เท่านั้นที่อ่าน/เพิ่ม/แก้/ลบได้
do $$
declare t text;
begin
  foreach t in array array['dept','doc_type','news_category','news','circular','circular_file',
                           'hub_section','hub_item','phone_directory','dashboard']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "admin full access" on public.%I', t);
    execute format('create policy "admin full access" on public.%I for all to authenticated using (public.is_admin()) with check (public.is_admin())', t);
    execute format('revoke all on public.%I from anon', t);
  end loop;
end $$;

alter table public.admin_users enable row level security;   -- ไม่มี policy = เข้าถึงผ่าน API ไม่ได้
revoke all on public.admin_users from anon, authenticated;

